"""Generate reproducible offline Module 1 corpus observations without network calls."""
from __future__ import annotations
import argparse, asyncio, hashlib, json, sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/"src"))
from links.services.analyser import check_brand, check_lexical
from links.services.checks.normalise import normalize
from links.models import CheckResult
from links.services.registry import Context
from links.services.risk import classify, confidence_for


def load(name):
    path=ROOT/"tests"/"corpus"/name
    return path,json.loads(path.read_text(encoding="utf-8-sig"))

async def evaluate(case):
    ctx=Context(case["input"]); ctx.nurl=normalize(case["input"])
    findings=await check_lexical(ctx)+await check_brand(ctx)
    checks=[CheckResult(check_id=cid,status="ok" if cid in {"normalise","lexical","brand_impersonation"} else "unavailable",reason=None if cid in {"normalise","lexical","brand_impersonation"} else "omitted from offline static corpus run") for cid in ("normalise","lexical","brand_impersonation","redirect_chain","password_form","dns","rdap","intel_safebrowsing","intel_virustotal","intel_urlhaus")]
    risk,groups=classify(findings,checks,chain_complete=False)
    fired=sorted(f.id for f in findings)
    return {"input":case["input"],"category":case.get("category","uncategorized"),"expected":case.get("expected_classes",[case.get("expected_class_min","unspecified"),case.get("expected_class_max","unspecified")]),"observed":risk,"findings":fired,"groups":[g["group"] for g in groups],"coverage":"3/10 (offline static checks only)","confidence":confidence_for(checks,False)}


def render(output:Path):
    sources=[load("benign.json"),load("suspicious.json")]
    cases=[]
    for _,items in sources:
        for case in items:
            if case.get("fetch") is not False: raise ValueError("offline corpus entries must set fetch=false")
            cases.append(asyncio.run(evaluate(case)))
    benign=[x for x in cases if x["category"].startswith(("benign","new_legitimate","shared_hosting"))]
    adversarial=[x for x in cases if x not in benign]
    counts=Counter(rule for item in benign for rule in item["findings"])
    category=defaultdict(lambda:[0,0])
    for item in adversarial:
        category[item["category"]][1]+=1
        if item["observed"] in {"suspicious","high","confirmed_malicious"}: category[item["category"]][0]+=1
    lines=["# Module 1 offline corpus results","","Generated by `uv run python scripts/build_test_results.py`. This is a deterministic, static-only evaluation: no URL in these corpora is fetched and no live intelligence services are called.","", "## Reproducibility",""]
    for path,_ in sources: lines.append(f"- `{path.relative_to(ROOT).as_posix()}` SHA-256: `{hashlib.sha256(path.read_bytes()).hexdigest()}`")
    lines.extend(["","## Observations","","| Category | Input | Expected | Observed | Rules | Coverage | Confidence |","|---|---|---|---|---|---|---|"])
    for item in cases:
        rules=", ".join(item["findings"]) or "(none)"
        expected=" / ".join(item["expected"]) if isinstance(item["expected"],list) else str(item["expected"])
        lines.append(f"| {item['category']} | `{item['input']}` | {expected} | {item['observed']} | {rules} | {item['coverage']} | {item['confidence']} |")
    lines.extend(["","## Benign rule firing counts","", "| Rule | Count |", "|---|---:|"])
    for rule,count in sorted(counts.items()): lines.append(f"| `{rule}` | {count} |")
    lines.extend(["","## Benign false-positive log","","| Input | Observed | Decision |","|---|---|---|"])
    suspicious=[x for x in benign if x["observed"]=="suspicious"]
    if suspicious:
        for item in suspicious: lines.append(f"| `{item['input']}` | suspicious | Pending manual review |")
    else: lines.append("| (none in current sample) | — | No manual conclusion implied |")
    lines.extend(["","## Adversarial detection by category","","| Category | Detected suspicious or higher | Count | Rate |", "|---|---:|---:|---:|"])
    if category:
        for name,(hits,total) in sorted(category.items()): lines.append(f"| {name} | {hits} | {total} | {hits/total:.0%} |")
    else: lines.append("| (none) | 0 | 0 | — |")
    lines.extend(["","## Known evasion log","","- Brands absent from the curated dataset are not detected reliably.","- Whole-script homographs without mixed scripts may evade the current rule.","- Keyword-only phishing without a brand signal can evade static brand rules.","- A legitimate compromised site can look benign in static analysis.","","## Scope and limitations","",f"Current sample size: {len(benign)} benign and {len(adversarial)} adversarial. The plan requires at least 40 of each and dated verification of benign entries; this sample does not meet that acceptance threshold.","Coverage and confidence are from the three local checks in this offline harness, not from a full API report. Redirect, password, DNS, RDAP, external reputation, Redis, Docker, and live PostgreSQL behaviors are not measured here. Suspicious cases and any corpus false positives require human disposition before the plan's false-positive criteria can pass.",""])
    output.parent.mkdir(parents=True,exist_ok=True); output.write_text("\n".join(lines),encoding="utf-8")
    print(f"Wrote {output.relative_to(ROOT)} ({len(benign)} benign, {len(adversarial)} adversarial)")

if __name__=="__main__":
    parser=argparse.ArgumentParser(description=__doc__); parser.add_argument("--output",type=Path,default=ROOT/"tests"/"RESULTS.md"); render(parser.parse_args().output)
